let CURRENT_LANG = localStorage.getItem("emudra_lang") || "mr";

/**
 * Switch current language and update all i18n DOM elements
 */
function setLanguage(lang) {
  if (lang !== "mr" && lang !== "en") lang = "mr";
  CURRENT_LANG = lang;
  localStorage.setItem("emudra_lang", lang);
  document.documentElement.lang = lang;
  
  // Update all elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(elem => {
    const key = elem.getAttribute("data-i18n");
    if (I18N_DATA[lang] && I18N_DATA[lang][key]) {
      if (elem.tagName === "INPUT" || elem.tagName === "TEXTAREA") {
        if (elem.hasAttribute("placeholder")) {
          elem.placeholder = I18N_DATA[lang][key];
        }
      } else {
        elem.innerHTML = I18N_DATA[lang][key];
      }
    }
  });

  // Update language toggle button text
  const langToggleBtn = document.getElementById("lang-toggle-btn");
  if (langToggleBtn) {
    langToggleBtn.innerHTML = `<i class="fa-solid fa-language"></i> ${I18N_DATA[lang].lang_btn}`;
  }

  // Trigger custom event so other modules can re-render dynamic items
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

